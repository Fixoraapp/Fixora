import { City, Country, Region } from '../types/location';

const city = (regionId: string, id: string, name_ru: string, name_en = name_ru, name_hy?: string): City => ({
  id,
  region_id: regionId,
  name_ru,
  name_en,
  name_hy,
});

const region = (
  id: string,
  country_iso2: string,
  name_ru: string,
  name_en: string,
  type_ru: string,
  type_en: string,
  capital_ru: string,
  capital_en: string,
  cities: City[] = [],
  parent_region_id?: string,
  name_hy?: string,
): Region => ({
  id,
  country_iso2,
  parent_region_id,
  name_ru,
  name_en,
  name_hy,
  type_ru,
  type_en,
  capital_ru,
  capital_en,
  cities: cities.length > 0 ? cities : [city(id, `${id}-capital`, capital_ru, capital_en)],
});

const district = (id: string, name_ru: string, name_en: string): Region =>
  region(id, 'RU', name_ru, name_en, 'федеральный округ', 'Federal District', '', '', []);

const subject = (
  id: string,
  districtId: string,
  name_ru: string,
  name_en: string,
  type_ru: string,
  type_en: string,
  capital_ru: string,
  capital_en: string,
): Region => region(id, 'RU', name_ru, name_en, type_ru, type_en, capital_ru, capital_en, [], districtId);

const usState = (id: string, name: string, capital: string): Region =>
  region(id, 'US', name, name, 'штат', 'State', capital, capital);

const canadaRegion = (id: string, name: string, type_en: 'Province' | 'Territory', capital: string): Region =>
  region(id, 'CA', name, name, type_en === 'Province' ? 'провинция' : 'территория', type_en, capital, capital);

